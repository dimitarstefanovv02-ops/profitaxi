const SATURDAY = ['Събота е. Някой ще празнува, а ти ще го закараш.'];
const SUNDAY = ['Неделя: спокоен ден за курсове до мама и обратно.'];
const MONDAY = ['Понеделник е. Всички мразят понеделник, освен таксиметърът.'];

export function pickQuote({ goal, streak, worked } = {}) {
  const now = new Date();
  const hour = now.getHours();
  const wd = weekdayIdx(todayStr());
  const pool = [...GENERAL];
  if (hour >= 5 && hour < 11) pool.push(...MORNING, ...MORNING);
  if (hour >= 18 || hour < 3) pool.push(...EVENING, ...EVENING);
  if (wd === 4) pool.push(...FRIDAY, ...FRIDAY, ...FRIDAY);
  if (wd === 5) pool.push(...SATURDAY, ...SATURDAY);
  if (wd === 6) pool.push(...SUNDAY, ...SUNDAY);
  if (wd === 0) pool.push(...MONDAY, ...MONDAY);
  if (goal?.done) pool.push('Целта за месеца е изпълнена! Всичко от тук нататък е бонус.', 'Цел: ✓. Сега може и по-голяма.');
  else if (goal && goal.pct >= 0.75) pool.push('Остава съвсем малко до целта. Финалната права!', `Само още ${Math.max(1, goal.shiftsNeeded || 1)} добри смени.`);
  else if (goal && goal.pct >= 0.4) pool.push('Средата на пътя е минала. Продължавай така.');
  if (streak >= 5) pool.push(`${streak} поредни дни на смяна. Машина си!`, `Серия от ${streak} дни. Колата вече те познава по походката.`);
  if (worked === false && hour >= 12) pool.push('Днес още не си започнал. Таксиметърът скучае.');
  return pool;
}

// Връща едно съобщение; seed позволява да се сменя с натискане
export function quoteFor(ctx, seed = 0) {
  const pool = pickQuote(ctx);
  const day = Number(todayStr().replace(/-/g, '')) + new Date().getHours();
  return pool[(day + seed * 7) % pool.length];
}
