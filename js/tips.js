const KEY = 'profitaxi.tips';
const seen = () => { try { return JSON.parse(localStorage.getItem(KEY) || '[]'); } catch { return []; } };
const mark = (k) => { try { localStorage.setItem(KEY, JSON.stringify([...new Set([...seen(), k])])); } catch { /* */ } };

export function tipFor(name) {
  const text = TIPS[name];
  if (!text || seen().includes(name)) return null;
  const el = h('div', { class: 'first-tip', role: 'note' },
    h('span', { class: 'ft-ic' }, icon('sparkle', 18)),
    h('p', null, text),
    h('button', { class: 'ft-ok', type: 'button', 'aria-label': 'Разбрах', onclick: () => { mark(name); el.remove(); } }, 'Разбрах'));
  return el;
}
export const resetTips = () => { try { localStorage.removeItem(KEY); } catch { /* */ } };
